"""
Day: 2
Concept: subscripting and data types
Summary: Learning about different data types in Python and how to manipulate strings.
"""

print("Hello, World!"[0])

# [] is used for subscripting, which allows you to access individual characters in a string by their index. In this case, it accesses the first character of the string "Hello, World!", which is "H".

print("Hello, World!"[-1])

# string
print("123" + "456")

# integers
print(123 + 456)

# large numbers
print(123_456_789 + 987_654_321)

# float
print(3.14 + 2.71)

# boolean
print(True)
print(False)
